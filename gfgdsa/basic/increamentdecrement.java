public class increamentdecrement {
    public static void main(String[] args) {
        int x=10;
        System.out.println(x++);
        System.out.println(x);

        int y=10;
        System.out.println(++y);
        System.out.println(y);

        int z=10;
        System.out.println(z--);
        System.out.println(z);

        int v=10;
        System.out.println(--v);
        System.out.println(v);
    }
}
